"""
scre_retention_eval.py
=======================
LLM-graded meaning-retention benchmark for SCRE.

Unlike ``scre_eval.py`` (which uses an offline spaCy extractive heuristic
and a lexical MRS proxy), this evaluates retention by asking two
independent LLM calls to answer the same question -- once from the full,
unreduced document, once from SCRE's reduced context -- then asking a third
LLM call to judge whether the two answers convey the same meaning. This is
the actual test of whether SCRE's reduction retains meaning, as opposed to
comparing raw text overlap between the two contexts.

Requires a running local Ollama instance with the configured model pulled
(see ``scre.scre_answer_engine.DEFAULT_MODEL_NAME``).
"""
from pathlib import Path

from qa_dataset import FACT_QA_DATASET, WORKFLOW_QA_DATASET, DECISION_QA_DATASET, REASONING_QA_DATASET, CAUSAL_QA_DATASET
from scre.scre_answer_engine import answer_with_ollama, judge_meaning_retention
from scre.scre_pipeline import run_scre


def print_result(item: dict, result: dict, full_answer: str, verdict: dict) -> bool:
    metrics = result["metrics"]
    reduced_answer = result["answer"]["answer"]

    print("\n" + "=" * 80)
    print(f"QUESTION: {item['question']}")
    print("=" * 80)
    print(
        "Estimated tokens:",
        metrics["original_estimated_tokens"],
        "->",
        metrics["reduced_estimated_tokens"],
        f"({metrics['reduction_ratio']:.2%} reduction)",
    )
    print("Full-context answer:   ", full_answer)
    print("Reduced-context answer:", reduced_answer)
    print("Judge verdict:", "MATCH" if verdict["match"] else "MISMATCH", "-", verdict["reason"])

    return verdict["match"]


def run_dataset(name: str, dataset: list[dict], context_window: int) -> dict:
    retained = 0
    total_reduction = 0.0
    total_items = len(dataset)

    print("\n" + "#" * 80)
    print(f"DATASET: {name}")
    print("#" * 80)

    for item in dataset:
        document = Path(item["document_path"]).read_text(encoding="utf-8")

        # Reduced-context answer, generated by the same Ollama model.
        result = run_scre(
            document,
            item["question"],
            max_sentences=4,
            context_window=context_window,
            answer_mode="ollama",
        )

        # Full-context answer, from the same model over the unreduced document,
        # so any difference in the judge's verdict is attributable to the
        # reduction, not to a different model or prompting.
        full_answer = answer_with_ollama(
            reduced_context=document,
            user_question=item["question"],
        )

        verdict = judge_meaning_retention(
            question=item["question"],
            full_answer=full_answer,
            reduced_answer=result["answer"]["answer"],
        )

        if print_result(item, result, full_answer, verdict):
            retained += 1
        total_reduction += result["metrics"]["reduction_ratio"]

    retention_rate = retained / total_items
    avg_reduction = total_reduction / total_items

    print("\n" + "-" * 80)
    print(f"Meaning retention: {retained}/{total_items} ({retention_rate:.2%})")
    print(f"Average token reduction: {avg_reduction:.2%}")

    return {"retention_rate": retention_rate, "avg_reduction": avg_reduction}


if __name__ == "__main__":
    summary = {}

    summary["fact"] = run_dataset("Fact Retrieval", FACT_QA_DATASET, context_window=0)
    summary["reasoning"] = run_dataset("Reasoning Retrieval", REASONING_QA_DATASET, context_window=0)
    summary["workflow"] = run_dataset("Workflow Retrieval", WORKFLOW_QA_DATASET, context_window=0)
    summary["decision"] = run_dataset("Decision Retrieval", DECISION_QA_DATASET, context_window=0)
    summary["causal"] = run_dataset("Causal Retrieval", CAUSAL_QA_DATASET, context_window=0)

    print("\n" + "=" * 80)
    print("FINAL SUMMARY -- LLM-graded meaning retention")
    print("=" * 80)
    for ds_name, stats in summary.items():
        print(f"{ds_name.capitalize()}: Retention {stats['retention_rate']:.2%}, Reduction {stats['avg_reduction']:.2%}")
